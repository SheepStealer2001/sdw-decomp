"""Python copy of the instruction-length decoder in hook.c, used by tools/build_mods.py --check-hooks."""
NOMODRM_NOIMM = set(range(0x40, 0x60)) | {0x27, 0x2F, 0x37, 0x3F, 0x60, 0x61, 0x90, 0x91, 0x92, 0x93, 0x94, 0x95, 0x96,
    0x97, 0x98, 0x99, 0x9B, 0x9C, 0x9D, 0x9E, 0x9F, 0xA4, 0xA5, 0xA6, 0xA7, 0xAA, 0xAB, 0xAC, 0xAD, 0xAE, 0xAF, 0xC3,
    0xC9, 0xCB, 0xCC, 0xCE, 0xCF, 0xD7, 0xF4, 0xF5, 0xF8, 0xF9, 0xFA, 0xFB, 0xFC, 0xFD, 0x6C, 0x6D, 0x6E, 0x6F}
IMM8 = {0x04, 0x0C, 0x14, 0x1C, 0x24, 0x2C, 0x34, 0x3C, 0x6A, 0xA8, 0xCD, 0xE4, 0xE5, 0xE6, 0xE7} | set(range(0xB0, 0xB8))
REL8 = set(range(0x70, 0x80)) | {0xEB, 0xE0, 0xE1, 0xE2, 0xE3}
IMMZ = {0x05, 0x0D, 0x15, 0x1D, 0x25, 0x2D, 0x35, 0x3D, 0x68, 0xA9} | set(range(0xB8, 0xC0))
MODRM = set()
for base in (0x00, 0x08, 0x10, 0x18, 0x20, 0x28, 0x30, 0x38):
    MODRM |= {base, base + 1, base + 2, base + 3}
MODRM |= {0x62, 0x63, 0x84, 0x85, 0x86, 0x87, 0x88, 0x89, 0x8A, 0x8B, 0x8C, 0x8D, 0x8E, 0x8F, 0xC4, 0xC5, 0xD0, 0xD1,
          0xD2, 0xD3, 0xFE, 0xFF} | set(range(0xD8, 0xE0))
MODRM_IMM8 = {0x80, 0x82, 0x83, 0x6B, 0xC0, 0xC1, 0xC6}
MODRM_IMMZ = {0x81, 0x69, 0xC7}
PREFIX = {0x66, 0x67, 0xF2, 0xF3, 0x2E, 0x36, 0x3E, 0x26, 0x64, 0x65, 0xF0}


def modrm_len(code, i):
    """bytes taken by the ModRM byte at i and what follows it (SIB, displacement)"""
    m = code[i]; mod, rm = m >> 6, m & 7
    n = 1
    if mod != 3 and rm == 4:
        sib = code[i + 1]; n += 1
        if mod == 0 and (sib & 7) == 5:
            n += 4
    if mod == 1: n += 1
    elif mod == 2: n += 4
    elif mod == 0 and rm == 5: n += 4
    return n


def insn(code, i):
    """(length, kind) with kind None, 'rel32' (E8/E9/0F 8x, relocatable) or 'rel8' / 'bad' (not copyable)."""
    start = i; o16 = False
    while code[i] in PREFIX:
        o16 |= code[i] == 0x66; i += 1
    op = code[i]; i += 1
    z = 2 if o16 else 4
    if op == 0x0F:
        op2 = code[i]; i += 1
        if 0x80 <= op2 <= 0x8F: return i + 4 - start, 'rel32'
        if op2 in (0x31, 0xA2): return i - start, None
        if op2 in (0xA4, 0xAC, 0xBA): return i + modrm_len(code, i) + 1 - start, None
        if op2 in (0xAF, 0xB6, 0xB7, 0xBE, 0xBF, 0xA3, 0xAB, 0xB3, 0xBB, 0xA5, 0xAD) or 0x40 <= op2 <= 0x4F \
                or 0x90 <= op2 <= 0x9F:
            return i + modrm_len(code, i) - start, None
        return i - start, 'bad'
    if op in NOMODRM_NOIMM: return i - start, None
    if op in IMM8: return i + 1 - start, None
    if op in REL8: return i + 1 - start, 'rel8'
    if op in IMMZ: return i + z - start, None
    if op in (0xE8, 0xE9): return i + 4 - start, 'rel32'
    if op in (0xA0, 0xA1, 0xA2, 0xA3): return i + 4 - start, None
    if op in (0xC2, 0xCA): return i + 2 - start, None
    if op == 0xC8: return i + 3 - start, None
    if op in MODRM: return i + modrm_len(code, i) - start, None
    if op in MODRM_IMM8: return i + modrm_len(code, i) + 1 - start, None
    if op in MODRM_IMMZ: return i + modrm_len(code, i) + z - start, None
    if op in (0xF6, 0xF7):
        reg = (code[i] >> 3) & 7
        n = modrm_len(code, i)
        if reg in (0, 1): n += 1 if op == 0xF6 else z
        return i + n - start, None
    return i - start, 'bad'
