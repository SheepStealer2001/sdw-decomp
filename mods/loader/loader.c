/* The mod loader: a stand-in dinput8.dll. Put it next to SheepD3D.exe. The game imports one function from DINPUT8.dll,
 * DirectInput8Create, which this DLL forwards to the system's own dinput8.dll; Windows loads a DLL from the game's
 * folder before the system copy, so the loader runs inside the player's own, unmodified SheepD3D.exe.
 *
 * At process start (DllMain) it checks the exe by its SHA-1 and, if it is the PAL SheepD3D.exe (whose functions are at
 * the addresses in data/symbols*.csv, as this project's byte-identical build proves), hooks WinMain. When WinMain runs,
 * it loads every Mods\<Name>\<Name>.dll, calls its SdwModInit with the API (mods/kit/sdw_mod.h), and starts the game.
 * Everything it does is written to Mods\mods.log. With any other exe it only forwards DirectInput8Create. */
