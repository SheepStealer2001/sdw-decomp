/* ---------------------------------------------------------------------------------------------------------- log */

static void log_line(const char *fmt, ...)
{
    va_list ap;
    SYSTEMTIME t;
    if (!g_log)
        return;
    GetLocalTime(&t);
    fprintf(g_log, "%02d:%02d:%02d ", t.wHour, t.wMinute, t.wSecond);
    if (g_currentMod[0])
        fprintf(g_log, "[%s] ", g_currentMod);
    va_start(ap, fmt);
    vfprintf(g_log, fmt, ap);
    va_end(ap);
    fputc('\n', g_log);
    fflush(g_log);
}

