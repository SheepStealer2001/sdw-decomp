static int sha1_file(const char *path, char out[41])
{
    HCRYPTPROV prov = 0;
    HCRYPTHASH hash = 0;
    BYTE buf[65536], digest[20];
    DWORD got, len = sizeof digest;
    HANDLE f = CreateFileA(path, GENERIC_READ, FILE_SHARE_READ, 0, OPEN_EXISTING, 0, 0);
    int i, ok = 0;
    if (f == INVALID_HANDLE_VALUE)
        return 0;
    if (CryptAcquireContextA(&prov, 0, 0, PROV_RSA_FULL, CRYPT_VERIFYCONTEXT) &&
        CryptCreateHash(prov, CALG_SHA1, 0, 0, &hash)) {
        ok = 1;
        while (ReadFile(f, buf, sizeof buf, &got, 0) && got)
            ok &= CryptHashData(hash, buf, got, 0) != 0;
        ok &= CryptGetHashParam(hash, HP_HASHVAL, digest, &len, 0) != 0;
    }
    if (hash)
        CryptDestroyHash(hash);
    if (prov)
        CryptReleaseContext(prov, 0);
    CloseHandle(f);
    for (i = 0; ok && i < 20; i++)
        sprintf(out + 2 * i, "%02x", digest[i]);
    return ok;
}

