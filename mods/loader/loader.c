/* mod classes, registered again after every Scenaric_RegisterAllClasses (the game clears its registry on each load) */
typedef struct {
    SdwFactoryFn factory;
    void *iconA, *iconB;
    unsigned classFlags;
} ClassEntry; /* g_scenaricClassRegistry[200], 16 bytes each */
static struct {
    unsigned short id, like;
    SdwFactoryFn factory;
    char mod[64];
} g_classes[64];
static int g_nClasses;

static void bring_icons_and_text(ClassEntry *reg);

/* each class's two icon ids, as the game registers them (Scenaric_RegisterClass_2), for bringing an icon from
 * another level's .DAV */
static unsigned short g_iconIds[200][2];
static void(__cdecl *orig_Scenaric_RegisterClass_2)(unsigned short, void *, unsigned, unsigned short, unsigned short);
static void __cdecl ev_Scenaric_RegisterClass_2(unsigned short classId, void *factory, unsigned flags,
                                                unsigned short iconA, unsigned short iconB)
{
    if (classId < 200) {
        g_iconIds[classId][0] = iconA;
        g_iconIds[classId][1] = iconB;
    }
    orig_Scenaric_RegisterClass_2(classId, factory, flags, iconA, iconB);
}

static void(__cdecl *orig_Scenaric_RegisterAllClasses)(void);
static void __cdecl ev_Scenaric_RegisterAllClasses(void)
{
    ClassEntry *reg = (ClassEntry *)api_find("g_scenaricClassRegistry");
    int i;
    orig_Scenaric_RegisterAllClasses();
    if (reg)
        bring_icons_and_text(reg);
    for (i = 0; reg && i < g_nClasses; i++) {
        ClassEntry *e = &reg[g_classes[i].id];
        if (e->factory && e->factory != g_classes[i].factory) {
            lstrcpynA(g_currentMod, g_classes[i].mod, sizeof g_currentMod);
            log_line("class %u is the game's own: not replaced", g_classes[i].id);
            g_currentMod[0] = 0;
            continue;
        }
        *e = reg[g_classes[i].like];
        e->factory = g_classes[i].factory;
    }
}

static int hook_register_all(void) /* once */
{
    static int done, r;
    if (!done) {
        done = 1;
        r = api_hook("Scenaric_RegisterAllClasses", (void *)ev_Scenaric_RegisterAllClasses,
                     (void **)&orig_Scenaric_RegisterAllClasses);
    }
    return r;
}

static int api_register_class(unsigned short classId, SdwFactoryFn factory, unsigned short likeClassId)
{
    int i;
    if (classId >= 200 || likeClassId >= 200 || !factory || g_nClasses >= 64) {
        log_line("register_class %u: out of range (0-199)", classId);
        return -1;
    }
    for (i = 0; i < g_nClasses; i++)
        if (g_classes[i].id == classId)
            log_line("conflict: class %u is %s's too: this mod's factory is used", classId, g_classes[i].mod);
    if (hook_register_all() != 0)
        return -1;
    g_classes[g_nClasses].id = classId;
    g_classes[g_nClasses].like = likeClassId;
    g_classes[g_nClasses].factory = factory;
    lstrcpynA(g_classes[g_nClasses].mod, g_currentMod, sizeof g_classes[g_nClasses].mod);
    g_nClasses++;
    log_line("class %u registered (like class %u)", classId, likeClassId);
    return 0;
}

/* the game's Scenaric_CreateObject: the class's factory, or for a class without one (static scenery, class 12, among
 * others) the generic object its model type calls for */
static void *api_create_object(unsigned short classId, void *record)
{
    void *(__cdecl * create)(unsigned short, void *) =
        (void *(__cdecl *)(unsigned short, void *))api_find("Scenaric_CreateObject");
    return create ? create(classId, record) : 0;
}

/* ---------------------------------------------------------------------------------------------------------- mods */

/* ---- the mods: their manifests, load order, settings and the ones switched off ----
 * A mod folder may hold mod.txt (`key: value` lines: name, version, author, description, requires, after; the last
 * two list other mods' folder names) and settings.txt (`key = value`, read through api->setting). Mods\disabled.txt
 * lists the folders the Mods menu switched off (one per line). The load order is the folders' names, except that a
 * mod loads after those it `requires` or names in `after`; a mod whose requirement is missing or switched off is not
 * loaded. Mods\cache is the loader's own folder, not a mod. */
#define MAX_KEYS 32
typedef struct {
    char folder[64];
    char name[64], version[32], author[64], description[256];
    char requires[8][64], after[8][64];
    int nrequires, nafter, disabled, placed, switchedOff; /* disabled: not loaded; switchedOff: by the Mods menu */
    char keys[MAX_KEYS][48], values[MAX_KEYS][208];
    int nkeys;
} ModInfo;
static ModInfo g_modInfo[64];
static int g_nModInfo;
static SdwModApi g_apis[64]; /* one per mod: its own mod_dir and settings */
static char g_apiDirs[64][MAX_PATH];

static char *trim(char *s)
{
    char *e;
    while (*s == ' ' || *s == '\t')
        s++;
    e = s + strlen(s);
    while (e > s && (e[-1] == ' ' || e[-1] == '\t' || e[-1] == '\r' || e[-1] == '\n'))
        *--e = 0;
    return s;
}

static int split_list(char *value, char (*out)[64], int max) /* names separated by commas or spaces */
{
    int n = 0;
    char *tok = strtok(value, ", \t");
    while (tok && n < max) {
        lstrcpynA(out[n++], tok, 64);
        tok = strtok(0, ", \t");
    }
    return n;
}

/* each line of a text file as `key<sep>value` (sep ':' or '='), `#` starting a comment, to fn */
static void read_pairs(const char *path, void (*fn)(ModInfo *, char *, char *), ModInfo *m)
{
    char *text = read_text(path), *line, *next;
    if (!text)
        return;
    for (line = text; line && *line; line = next) {
        char *sep, *hash;
        next = strchr(line, '\n');
        if (next)
            *next++ = 0;
        if ((hash = strchr(line, '#')) != 0)
            *hash = 0;
        sep = strpbrk(line, ":=");
        if (!sep)
            continue;
        *sep = 0;
        fn(m, trim(line), trim(sep + 1));
    }
    free(text);
}

static void manifest_pair(ModInfo *m, char *key, char *value)
{
    if (!_stricmp(key, "name"))
        lstrcpynA(m->name, value, sizeof m->name);
    else if (!_stricmp(key, "version"))
        lstrcpynA(m->version, value, sizeof m->version);
    else if (!_stricmp(key, "author"))
        lstrcpynA(m->author, value, sizeof m->author);
    else if (!_stricmp(key, "description"))
        lstrcpynA(m->description, value, sizeof m->description);
    else if (!_stricmp(key, "requires"))
        m->nrequires = split_list(value, m->requires, 8);
    else if (!_stricmp(key, "after"))
        m->nafter = split_list(value, m->after, 8);
}

static void settings_pair(ModInfo *m, char *key, char *value)
{
    if (m->nkeys < MAX_KEYS) {
        lstrcpynA(m->keys[m->nkeys], key, sizeof m->keys[0]);
        lstrcpynA(m->values[m->nkeys++], value, sizeof m->values[0]);
    }
}

static const char *api_setting(const SdwModApi *self, const char *key, const char *fallback)
{
    int i = (int)(self - g_apis), k;
    if (i < 0 || i >= 64)
        return fallback;
    for (k = 0; k < g_modInfo[i].nkeys; k++)
        if (!_stricmp(g_modInfo[i].keys[k], key))
            return g_modInfo[i].values[k];
    return fallback;
}

static int api_setting_int(const SdwModApi *self, const char *key, int fallback)
{
    const char *v = api_setting(self, key, 0);
    char *end;
    long n;
    if (!v)
        return fallback;
    n = strtol(v, &end, 0);
    return end != v ? (int)n : fallback;
}

static int by_folder(const void *a, const void *b)
{
    return _stricmp(((const ModInfo *)a)->folder, ((const ModInfo *)b)->folder);
}

static ModInfo *find_mod(const char *folder)
{
    int i;
    for (i = 0; i < g_nModInfo; i++)
        if (!_stricmp(g_modInfo[i].folder, folder))
            return &g_modInfo[i];
    return 0;
}

/* the installed mods, read and ordered (also for the Mods menu) */
static void scan_mods(void)
{
    char pattern[MAX_PATH], path[MAX_PATH], *text;
    WIN32_FIND_DATAA fd;
    HANDLE h;
    g_nModInfo = 0;
    _snprintf(pattern, sizeof pattern, "%sMods\\*", g_gameDir);
    if ((h = FindFirstFileA(pattern, &fd)) == INVALID_HANDLE_VALUE)
        return;
    do {
        ModInfo *m;
        if (!(fd.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY) || fd.cFileName[0] == '.' ||
            !_stricmp(fd.cFileName, "cache") || g_nModInfo >= 64)
            continue;
        m = &g_modInfo[g_nModInfo++];
        memset(m, 0, sizeof *m);
        lstrcpynA(m->folder, fd.cFileName, sizeof m->folder);
        lstrcpynA(m->name, fd.cFileName, sizeof m->name);
        _snprintf(path, sizeof path, "%sMods\\%s\\mod.txt", g_gameDir, fd.cFileName);
        read_pairs(path, manifest_pair, m);
    } while (FindNextFileA(h, &fd));
    FindClose(h);
    qsort(g_modInfo, g_nModInfo, sizeof g_modInfo[0], by_folder);
    _snprintf(path, sizeof path, "%sMods\\disabled.txt", g_gameDir);
    if ((text = read_text(path)) != 0) {
        char *line, *next;
        for (line = text; line && *line; line = next) {
            ModInfo *m;
            next = strchr(line, '\n');
            if (next)
                *next++ = 0;
            if ((m = find_mod(trim(line))) != 0)
                m->disabled = m->switchedOff = 1;
        }
        free(text);
    }
}

/* the next mod to load: the first (by folder name) whose `requires` and `after` that are installed are loaded */
static ModInfo *next_in_order(void)
{
    int i, k;
    for (i = 0; i < g_nModInfo; i++) {
        ModInfo *m = &g_modInfo[i];
        int ready = !m->placed;
        for (k = 0; ready && k < m->nrequires; k++) {
            ModInfo *d = find_mod(m->requires[k]);
            ready = !d || d->placed || d->disabled;
        }
        for (k = 0; ready && k < m->nafter; k++) {
            ModInfo *d = find_mod(m->after[k]);
            ready = !d || d->placed || d->disabled;
        }
        if (ready)
            return m;
    }
    for (i = 0; i < g_nModInfo; i++) /* a cycle: the first left, as it is */
        if (!g_modInfo[i].placed) {
            log_line("%s: its requires / after go round in a circle: loaded in name order", g_modInfo[i].folder);
            return &g_modInfo[i];
        }
    return 0;
}

static void load_mods(void)
{
    char path[MAX_PATH];
    ModInfo *m;
    int loaded = 0, k;
    scan_mods();
    while ((m = next_in_order()) != 0) {
        int i = (int)(m - g_modInfo), missing = 0, r;
        char *dir = g_apiDirs[i];
        SdwModApi *api = &g_apis[i];
        HMODULE dll;
        SdwModInitFn init;
        m->placed = 1;
        lstrcpynA(g_currentMod, m->folder, sizeof g_currentMod);
        if (m->disabled) {
            log_line("switched off (Mods\\disabled.txt)");
            g_currentMod[0] = 0;
            continue;
        }
        for (k = 0; k < m->nrequires; k++) {
            ModInfo *d = find_mod(m->requires[k]);
            if (!d || d->disabled || !d->placed) {
                log_line("not loaded: it requires %s, which is %s", m->requires[k], !d ? "not installed" : "switched off");
                missing = 1;
            }
        }
        if (missing) {
            m->disabled = 1; /* so that what requires it is not loaded either */
            g_currentMod[0] = 0;
            continue;
        }
        _snprintf(dir, MAX_PATH, "%sMods\\%s\\", g_gameDir, m->folder);
        _snprintf(path, sizeof path, "%ssettings.txt", dir);
        read_pairs(path, settings_pair, m);
        _snprintf(path, sizeof path, "%s%s.dll", dir, m->folder);
        if (GetFileAttributesA(path) == INVALID_FILE_ATTRIBUTES) { /* no code: files\ and levels\ only */
            if (g_nMods < 64) {
                lstrcpynA(g_modDirs[g_nMods], dir, MAX_PATH);
                lstrcpynA(g_modNames[g_nMods], m->folder, 64);
                g_nMods++;
                loaded++;
                log_line("loaded%s%s (files and level patches only)", m->version[0] ? ", version " : "", m->version);
            }
            g_currentMod[0] = 0;
            continue;
        }
        dll = LoadLibraryA(path);
        if (!dll) {
            log_line("not loaded: %s (error %lu; a mod is Mods\\<Name>\\<Name>.dll)", path, GetLastError());
            m->disabled = 1;
            g_currentMod[0] = 0;
            continue;
        }
        init = (SdwModInitFn)GetProcAddress(dll, "SdwModInit");
        if (!init) {
            log_line("%s exports no SdwModInit; unloaded", path);
            FreeLibrary(dll);
            m->disabled = 1;
            g_currentMod[0] = 0;
            continue;
        }
        api->version = SDW_MOD_API_VERSION;
        api->game = g_gameName;
        api->mod_dir = dir;
        api->find = api_find;
        api->hook = api_hook;
        api->hook_address = api_hook_address;
        api->log = log_line;
        api->on_frame = api_on_frame;
        api->on_level_load = api_on_level_load;
        api->on_level_free = api_on_level_free;
        api->on_object_created = api_on_object_created;
        api->register_class = api_register_class;
        api->create_object = api_create_object;
        api->setting = api_setting;
        api->setting_int = api_setting_int;
        r = init(api);
        if (r == 0)
            log_line("loaded%s%s", m->version[0] ? ", version " : "", m->version);
        else
            log_line("SdwModInit returned %d: unloaded", r);
        if (r != 0) {
            FreeLibrary(dll);
            m->disabled = 1;
        } else {
            loaded++;
            if (g_nMods < 64) {
                lstrcpynA(g_modDirs[g_nMods], dir, MAX_PATH);
                lstrcpynA(g_modNames[g_nMods], m->folder, 64);
                g_nMods++;
            }
        }
        g_currentMod[0] = 0;
    }
    log_line("%d mod(s) loaded", loaded);
}

