/* An exe built from the source with changes (tools/build_fixed.py) has its functions and data at other addresses. Its
 * symbol file, <exe>.sdwsym beside it, gives them: "SDW symbols, SHA-1 <its hash>", then per line an original address
 * and that thing's address in this exe, sorted (the build writes it from the two builds' linker maps). Every address
 * of the symbol table goes through it; one it lacks is not in this exe. */
static unsigned (*g_translate)[2];
static int g_nTranslate;
static char *read_text(const char *path);

static int load_translation(const char *exe, const char *sha)
{
    char path[MAX_PATH], *text, *s, *dot;
    int n = 0, cap = 0;
    lstrcpynA(path, exe, sizeof path - 8);
    dot = strrchr(path, '.');
    if (dot && !strchr(dot, '\\'))
        *dot = 0;
    strcat(path, ".sdwsym");
    if (!(text = read_text(path))) {
        log_line("no symbol file %s", path);
        return 0;
    }
    s = strstr(text, "SHA-1 ");
    if (!s || strncmp(s + 6, sha, 40)) {
        log_line("%s is for another exe", path);
        free(text);
        return 0;
    }
    for (s = strchr(s, '\n'); s && *++s;) {
        unsigned a, b;
        if (sscanf(s, "%x %x", &a, &b) == 2) {
            if (n == cap) {
                void *grown = realloc(g_translate, (cap = cap ? cap * 2 : 4096) * sizeof *g_translate);
                if (!grown)
                    break;
                g_translate = (unsigned (*)[2])grown;
            }
            g_translate[n][0] = a;
            g_translate[n++][1] = b;
        }
        s = strchr(s, '\n');
        if (!s)
            break;
    }
    free(text);
    g_nTranslate = n;
    log_line("its symbol file: %d addresses (%s)", n, path);
    return n > 0;
}

static unsigned translate(unsigned addr)
{
    int lo = 0, hi = g_nTranslate - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (g_translate[mid][0] == addr)
            return g_translate[mid][1];
        if (g_translate[mid][0] < addr)
            lo = mid + 1;
        else
            hi = mid - 1;
    }
    return 0;
}

static void *api_find(const char *name)
{
    int lo = 0, hi = g_sdwSymbolCount - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2, c = strcmp(name, g_sdwSymbols[mid].name);
        if (!c && g_translate)
            return (void *)(size_t)translate(g_sdwSymbols[mid].addr);
        if (!c)
            return (void *)(size_t)g_sdwSymbols[mid].addr;
        if (c < 0)
            hi = mid - 1;
        else
            lo = mid + 1;
    }
    return 0;
}

/* which mod hooked what (a conflict report when two mods hook the same function: the later one runs first) */
static struct {
    void *target;
    char mod[64];
} g_hooked[256];
static int g_nHooked;

static int api_hook_address(void *target, void *replacement, void **original)
{
    char why[160];
    int r = hook_install(target, replacement, original, why, sizeof why), i;
    if (r) {
        log_line("hook at %p failed: %s", target, why);
        return r;
    }
    for (i = 0; i < g_nHooked; i++)
        if (g_hooked[i].target == target && strcmp(g_hooked[i].mod, g_currentMod))
            log_line("conflict: %p is hooked by %s too (%s runs first, then calls through to %s)", target,
                     g_hooked[i].mod, g_currentMod[0] ? g_currentMod : "the loader", g_hooked[i].mod);
    if (g_nHooked < 256) {
        g_hooked[g_nHooked].target = target;
        lstrcpynA(g_hooked[g_nHooked++].mod, g_currentMod[0] ? g_currentMod : "the loader", sizeof g_hooked[0].mod);
    }
    return 0;
}

static int api_hook(const char *name, void *replacement, void **original)
{
    void *target = api_find(name);
    int r;
    if (!target) {
        log_line("hook %s: no such name in the symbol tables", name);
        return -1;
    }
    r = api_hook_address(target, replacement, original);
    if (!r)
        log_line("hooked %s (%p)", name, target);
    return r;
}

