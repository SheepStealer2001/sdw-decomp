/* 0x404410 - the indices of the buttons pressed this frame, at most maxCount of them; returns how many. No callers. */
u16 InputDevice::GetPressedButtons(u16 *out, u16 maxCount)
{
    u16 i = 0;
    u16 n = 0;
    u16 *dst = out;
    while (i < buttonCount && n < maxCount) {
        if (buttonPressed[i] == 1) {
            dst[n] = i;
            n++;
        }
        i++;
    }
    return n;
}

