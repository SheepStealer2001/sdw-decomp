/* 0x404194 - axes from the raw values, and buttonPressed from buttonDown (see the file comment). */
long InputDevice::Update()
{
    u16 i;
    axisX = rawX / 65535.0f;
    if (axisX < -1.0f)
        axisX = -1.0f;
    else if (axisX > 1.0f)
        axisX = 1.0f;
    axisY = rawY / 65535.0f;
    if (axisY < -1.0f)
        axisY = -1.0f;
    else if (axisY > 1.0f)
        axisY = 1.0f;
    axisZ = rawZ / 65535.0f;
    if (axisZ < -1.0f)
        axisZ = -1.0f;
    else if (axisZ > 1.0f)
        axisZ = 1.0f;
    axisX = axisX * axisScaleX + axisOffsetX;
    axisY = axisY * axisScaleY + axisOffsetY;
    axisZ = axisZ * axisScaleZ + axisOffsetZ;
    for (i = 0; i < buttonCount; i++) {
        buttonPressed[i] = (buttonDown[i] && !buttonBlocked[i] && (!buttonDownPrev[i] || allowHeld)) ? 1 : 0;
        buttonDownPrev[i] = buttonDown[i];
    }
    return 0;
}

