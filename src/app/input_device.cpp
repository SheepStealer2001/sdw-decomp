/* 0x403ff1 - allocates and clears the button arrays (at most 0x100 buttons) and resets the axes and their calibration. */
void InputDevice::AllocButtons(u16 count, D3DApp *app)
{
    u16 i;
    if (count > 0x100)
        buttonCount = 0x100;
    else
        buttonCount = count;
    buttonDown = new u8[buttonCount];
    buttonPressed = new u8[buttonCount];
    buttonBlocked = new u8[buttonCount];
    buttonDownPrev = new u8[buttonCount];
    axisZ = 0.0f;
    axisY = 0.0f;
    axisX = 0.0f;
    rawZ = 0;
    rawY = 0;
    rawX = 0;
    memset(buttonPressed, 0, buttonCount);
    memset(buttonDown, 0, buttonCount);
    axisScaleZ = 1.0f;
    axisScaleY = 1.0f;
    axisScaleX = 1.0f;
    axisOffsetZ = 0.0f;
    axisOffsetY = 0.0f;
    axisOffsetX = 0.0f;
    for (i = 0; i < buttonCount; i++) {
        buttonDownPrev[i] = 0;
        buttonBlocked[i] = 0;
    }
    pApp = app;
}

